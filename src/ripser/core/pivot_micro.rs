//! Attribution micro-benchmark for the pivot map.
//!
//! The apparent fast path inserts one entry per enumerated column. On the
//! real ASA matrix that is 286,562,199 inserts into an `FxHashMap<i64,
//! (usize, i16)>` whose keys are 3-simplex indices spread over
//! [0, C(1200,4)) = [0, 86e9) -- 0.33% dense. The map reserves 2^29 buckets,
//! i.e. ~13.4 GB.
//!
//! Timing that inside the real run is impossible without bias: the region runs
//! 2.9e8 times, so two `Instant::now()` calls per iteration (~50 ns each)
//! would cost more than the operation being priced. So price the data
//! structure on its own, with no algorithm around it.
//!
//! Keys are generated by an odd-multiplier bijection mod 2^37:
//! `key = i.wrapping_mul(K) & (2^37 - 1)` is injective, costs one multiply and
//! one AND, and lands every key in the same magnitude range as the real ones.
//! Generating keys on the fly matters -- materialising a 286e6-element key
//! array would add 2.3 GB of its own traffic and contaminate the measurement.

#[cfg(test)]
mod tests {
    use rustc_hash::FxHashMap;
    use std::time::Instant;

    /// Matches the ASA dim=2 insert count exactly.
    const N: usize = 286_562_199;
    /// 2^37 = 137_438_953_472, the same magnitude as C(1200,4) = 85_972_142_200.
    const KEY_MASK: u64 = (1 << 37) - 1;
    const ODD: u64 = 2_654_435_761;

    #[test]
    fn price_pivot_insert_against_table_size() {
        // ---- arm A: the real thing, ~13.4 GB -----------------------------
        let t0 = Instant::now();
        let mut big: FxHashMap<i64, (usize, i16)> = FxHashMap::default();
        big.reserve(N);
        let t_reserve = t0.elapsed();
        let t1 = Instant::now();
        for i in 0..N as u64 {
            let key = ((i.wrapping_mul(ODD)) & KEY_MASK) as i64;
            big.insert(key, (i as usize, 1));
        }
        let t_insert = t1.elapsed();
        let big_len = big.len();
        drop(big);

        // ---- arm B: same insert count, cache-resident table --------------
        // Keys collapse onto 2^16 distinct values, so the map never grows
        // past ~2^18 buckets (~6 MB). The insert arithmetic is identical;
        // only the memory footprint differs.
        let t2 = Instant::now();
        let mut small: FxHashMap<i64, (usize, i16)> = FxHashMap::default();
        small.reserve(1 << 16);
        let t_reserve_small = t2.elapsed();
        let t3 = Instant::now();
        for i in 0..N as u64 {
            let key = (((i.wrapping_mul(ODD)) & KEY_MASK) & 0xFFFF) as i64;
            small.insert(key, (i as usize, 1));
        }
        let t_insert_small = t3.elapsed();
        let small_len = small.len();

        let big_ns = t_insert.as_secs_f64() / N as f64 * 1e9;
        let small_ns = t_insert_small.as_secs_f64() / N as f64 * 1e9;

        println!("PIVOTMICRO inserts={N}");
        println!(
            "  big   (~13.4 GB): reserve={:.2}s insert={:.2}s  {:.1} ns/insert  distinct={}",
            t_reserve.as_secs_f64(),
            t_insert.as_secs_f64(),
            big_ns,
            big_len
        );
        println!(
            "  small (~6 MB)   : reserve={:.4}s insert={:.2}s  {:.1} ns/insert  distinct={}",
            t_reserve_small.as_secs_f64(),
            t_insert_small.as_secs_f64(),
            small_ns,
            small_len
        );
        println!(
            "  MARGINAL COST OF TABLE SIZE: {:.2}s  ({:.0} ns/insert of the {:.0} ns/insert total)",
            t_insert.as_secs_f64() - t_insert_small.as_secs_f64(),
            big_ns - small_ns,
            big_ns
        );
        // Distinctness is the whole point of the comparison; if the generator
        // ever stops being injective arm A silently degenerates into arm B.
        assert_eq!(big_len, N, "key generator is not injective");
        assert_eq!(small_len, 1 << 16, "masked key count is wrong");
    }
}

/// The linear-scan unrank that `fill_vertices` used before, kept verbatim as
/// the oracle for the binary-search version.
#[cfg(test)]
fn fill_vertices_linear(
    binomial_coeff: &crate::ripser::utils::BinomialCoeffTable,
    n: crate::ripser::types::IndexT,
    index: crate::ripser::types::IndexT,
    dim: crate::ripser::types::IndexT,
    out: &mut [crate::ripser::types::IndexT],
) -> usize {
    let count = (dim + 1) as usize;
    let mut idx = index;
    let mut k = dim + 1;
    let mut pos = count;
    for i in (0..n).rev() {
        if k > 0 && idx >= binomial_coeff.get(i, k) {
            idx -= binomial_coeff.get(i, k);
            pos -= 1;
            out[pos] = i;
            k -= 1;
        }
        if k == 0 {
            break;
        }
    }
    count
}

/// The binary-search unrank currently in `MatrixReducer::fill_vertices`,
/// mirrored here so it can be checked against the linear oracle without
/// constructing a full reducer (which needs a distance matrix).
#[cfg(test)]
fn fill_vertices_binary(
    binomial_coeff: &crate::ripser::utils::BinomialCoeffTable,
    n: crate::ripser::types::IndexT,
    index: crate::ripser::types::IndexT,
    dim: crate::ripser::types::IndexT,
    out: &mut [crate::ripser::types::IndexT],
) -> usize {
    let count = (dim + 1) as usize;
    let mut idx = index;
    let mut k = dim + 1;
    let mut pos = count;
    let mut hi = n;
    while k > 0 {
        let mut lo = k - 1;
        let mut top = hi;
        while lo + 1 < top {
            let mid = lo + ((top - lo) >> 1);
            if binomial_coeff.get(mid, k) <= idx {
                lo = mid;
            } else {
                top = mid;
            }
        }
        out[pos - 1] = lo;
        pos -= 1;
        idx -= binomial_coeff.get(lo, k);
        hi = lo;
        k -= 1;
    }
    count
}

#[cfg(test)]
mod unrank_tests {
    use super::*;
    use crate::ripser::types::IndexT;
    use crate::ripser::utils::BinomialCoeffTable;

    /// Exhaustive at small n, strided at large n. A strided sweep alone can
    /// miss the boundaries that matter most (index 0, and the largest valid
    /// index for each dim), so both are covered explicitly.
    #[test]
    fn binary_unrank_matches_linear_scan() {
        let mut total = 0usize;
        for n in [4usize, 6, 12, 40] {
            let n_t: IndexT = n as IndexT;
            let table = BinomialCoeffTable::new(n_t, 6).expect("binomial table");
            for dim in 1..=3 as IndexT {
                let k = dim + 1;
                // Largest valid index for this (n, k): C(n, k) - 1.
                let top = table.get(n_t - 1, k);
                let mut idx: IndexT = 0;
                let mut checked = 0usize;
                loop {
                    let mut a = [0 as IndexT; 16];
                    let mut b = [0 as IndexT; 16];
                    fill_vertices_linear(&table, n_t, idx, dim, &mut a);
                    fill_vertices_binary(&table, n_t, idx, dim, &mut b);
                    assert_eq!(
                        a, b,
                        "n={n} dim={dim} idx={idx}: linear {a:?} vs binary {b:?}"
                    );
                    checked += 1;
                    if idx >= top {
                        break;
                    }
                    idx += if n <= 12 { 1 } else { 7 };
                }
                // n=4, dim=3 has C(4,4)-1 == 0 as its whole index space, so a
                // single step is the correct answer there, not a vacuous test.
                // Totals are accumulated across combinations instead.
                total += checked;
            }
        }
        assert!(total > 200, "sweep only checked {total} indices");
    }
}
